const {chromium}=require('playwright');
const express=require('express');
const assert=require('node:assert/strict');
const {installMock}=require('./mock-projetos.cjs');
const path=require('node:path');
const os=require('node:os');

(async()=>{
 const app=express();app.use(express.static(process.cwd()));const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.on('listening',r));
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1500,height:960},reducedMotion:'reduce'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('https://**/*',r=>r.fulfill({body:'',contentType:'text/javascript'}));
  await page.route('https://fixture/**',r=>r.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="700"><rect width="1000" height="700" fill="#a7937b"/></svg>'}));
  await page.addInitScript(installMock,{token:true});
  await page.goto(`http://127.0.0.1:${server.address().port}/Modulos/Comercial/Catalogo/catalogo.html`);
  await page.locator('[data-gateway-tile="projetos"]').click();
  await page.locator('[data-cpj="layouts"]').click();
  await page.locator('[data-modelo="classico"]').click();
  await page.locator('dialog[open] [name="nome"]').fill('Original');
  await page.locator('dialog[open] button[type="submit"]').click();
  await page.locator('[data-design-brief]').waitFor();
  assert.equal(await page.locator('[data-design-style] option').count(),8);
  await page.locator('[data-design-style]').selectOption('romantico');
  const frame=await (await page.locator('[data-lay-iframe]').elementHandle()).contentFrame();
  await frame.locator('.pj-root').waitFor();
  await page.evaluate(()=>{
    window.designCalls=[];
    window.CatalogCredits.invoke=async(name,options)=>{
      window.designCalls.push({name,body:options.body});
      if(window.failDesign)return{error:{message:'Serviço temporariamente indisponível'}};
      return{data:{ok:true,design:{nome:'Jardim romântico',conceito:'Rosé e letras elegantes para criar uma atmosfera acolhedora.',modelo:'romantico',fonte:'elegante',principal:'#302020',destaque:'#865142',fundo:'#fffafa',suave:'#f1e0dd',capa:'lateral',movimento:'suave',renders:'destaque',pdf_orientacao:'retrato',espaco:'amplo',abertura:'Uma nova história',subtitulo:'Celebrar juntos.',titulo:'Um encontro especial',introducao:'Explore os ambientes preparados para este dia.',encerramento:'Vamos celebrar.'}}};
    };
  });
  await page.locator('[data-design-brief]').fill('Uma festa romântica com tons naturais e fotografia ampla.');
  const original=await page.evaluate(()=>JSON.stringify(window.mockdb.layouts));
  await page.locator('[data-design-generate]').click();
  await page.locator('[data-design-result]:not([hidden])').waitFor();
  await frame.locator('.pj-root[data-identidade="romantico"]').waitFor();
  assert.equal(await page.locator('.lay-grupo').first().getAttribute('disabled'),'');
  await frame.evaluate(()=>{window.print=()=>{window.__pdfReviewed=true;};});
  await page.locator('[data-design-pdf]').click();
  await frame.waitForFunction(()=>window.__pdfReviewed===true);
  assert.equal(await page.evaluate(()=>JSON.stringify(window.mockdb.layouts)),original,'Prévia da IA não altera layouts salvos');
  const request=await page.evaluate(()=>window.designCalls[0]);
  assert.equal(request.body.action,'design_presentation');assert.equal(request.body.catalog_token,'test');
  assert.equal(request.body.scene.estilo,'romantico');
  assert.equal(request.body.scene.ambientes.length,2);
  await frame.locator('.pj-nav-list a[href="#amb-1"]').click();
  assert.ok(await frame.locator('#amb-1').isVisible());
  assert.equal(await frame.locator('#amb-0').isVisible(),false);
  assert.equal(await frame.locator('.pj-cover').isVisible(),false);
  await frame.locator('.pj-nav-list a[href="#inicio"]').click();
  await page.locator('[data-design-discard]').click();
  assert.equal(await page.locator('.lay-grupo').first().getAttribute('disabled'),null);
  await frame.locator('.pj-root[data-identidade="classico"]').waitFor();
  assert.equal(await page.evaluate(()=>JSON.stringify(window.mockdb.layouts)),original);
  await page.evaluate(()=>{window.failDesign=true;});
  await page.locator('[data-design-generate]').click();
  await page.waitForFunction(()=>document.querySelector('[data-design-status]').textContent.includes('indisponível'));
  assert.equal(await page.locator('[data-design-generate]').isEnabled(),true);
  await page.evaluate(()=>{window.failDesign=false;});
  await page.locator('[data-design-generate]').click();
  await page.locator('[data-design-result]:not([hidden])').waitFor();
  await page.locator('[data-design-apply]').click();
  await page.waitForFunction(()=>window.mockdb.layouts.length===2);
  assert.equal(await page.evaluate(()=>window.mockdb.layouts[0].nome),'Original');
  assert.equal(await page.evaluate(()=>window.mockdb.calls.some(c=>/compartilhar|publicar/.test(c.name))),false);
  await page.screenshot({path:path.join(os.tmpdir(),'catalogo-designer-ia.png')});
  assert.deepEqual(errors,[]);
  console.log('OK: briefing, prévia sem salvar, ambientes, descarte, falha recuperável e nova versão sem publicar.');
 }finally{await browser.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
