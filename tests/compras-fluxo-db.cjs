const {PGlite}=require('@electric-sql/pglite');
const fs=require('node:fs');const assert=require('node:assert/strict');
async function createDB(){
 const db=new PGlite();
 await db.exec(`create schema auth;create schema storage;create role anon;create role authenticated;
 create function auth.uid() returns uuid language sql as $$select '00000000-0000-0000-0000-000000000001'::uuid$$;
 create function auth.jwt() returns jsonb language sql as $$select '{"user_metadata":{"nome":"Teste"}}'::jsonb$$;
 create function public.eh_membro_empresa(uuid) returns boolean language sql as $$select $1='10000000-0000-0000-0000-000000000001'::uuid$$;
 create function public.funcionario_tabela_permitida(uuid,text,text) returns boolean language sql as $$select true$$;
 create table empresas(id uuid primary key);
 create table insumos(id uuid primary key,empresa_id uuid,nome text,codigo text,unidade text,estoque_atual numeric default 0);
 create table fornecedores(id uuid primary key,empresa_id uuid,nome_fantasia text,nome_razao_social text,documento text);
 create table almoxarifado_compras(id uuid primary key default gen_random_uuid(),empresa_id uuid,fornecedor text,numero_nf text,chave_nfe text,status text,itens jsonb,valor_total numeric,origem_importacao text,data_compra date);
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(bucket_id text,name text);
 create function storage.foldername(text) returns text[] language sql as $$select string_to_array($1,'/')$$;
 insert into empresas values('10000000-0000-0000-0000-000000000001'),('10000000-0000-0000-0000-000000000002');
 insert into insumos(id,empresa_id,nome,codigo,unidade) values('20000000-0000-0000-0000-000000000001','10000000-0000-0000-0000-000000000001','Madeira','MAD1','un');
 insert into fornecedores values('30000000-0000-0000-0000-000000000001','10000000-0000-0000-0000-000000000001','Fornecedor A','Fornecedor A','123');`);
 await db.exec(fs.readFileSync('supabase/migrations/20261020000100_compras_tecnoweld.sql','utf8'));
 return db;
}
async function main(){
 const db=await createDB();
 const empresa='10000000-0000-0000-0000-000000000001',material='20000000-0000-0000-0000-000000000001',supplier='30000000-0000-0000-0000-000000000001';
 const call=async(action,data={},tenant=empresa)=>(await db.query('select compras_operar($1,$2,$3::jsonb) as result',[tenant,action,JSON.stringify(data)])).rows[0].result;
 await assert.rejects(()=>call('listar',{tipo:'pedido'},'10000000-0000-0000-0000-000000000002'),/Acesso negado/);
 const need=await call('criar_necessidade',{descricao_item:'Madeira',quantidade:4,unidade:'un'});
 assert.equal(need.status,'aguardando_vinculo');
 await call('vincular_material',{id:need.id,material_id:material});
 const payload={supplier_ids:[supplier],items:[{nome:'Madeira',codigo:'MAD1',material_id:material,unidade:'un',quantidade_cotada:4,need_allocations:[{purchase_request_id:need.id,quantidade_alocada:4}]}]};
 const quote=await call('criar_cotacao',payload);
 await assert.rejects(()=>call('criar_cotacao',payload),/disponível/);
 await call('salvar_proposta',{id:quote.id,supplier_id:supplier,header:{frete:10,condicao_pagamento:'30 dias'},items:[{quotation_item_id:quote.items[0].id,valor_unitario:25,nao_cotado:false}]});
 const result=await call('gerar_pedidos',{id:quote.id,selections:[{quotation_item_id:quote.items[0].id,supplier_id:supplier,quantidade:4}]});
 assert.equal(result.orders.length,1);assert.equal(result.orders[0].valor_total,110);
 await assert.rejects(()=>call('gerar_pedidos',{id:quote.id,selections:[]}),/convertida/);
 assert.equal((await call('consultar',{id:need.id})).status,'comprada');
 await call('cancelar_pedido',{id:result.orders[0].id,motivo:'Fornecedor sem estoque'});
 assert.equal((await call('consultar',{id:need.id})).quantidade_faltante,4);
 const q2=await call('criar_cotacao',payload);
 await call('salvar_proposta',{id:q2.id,supplier_id:supplier,header:{frete:0},items:[{quotation_item_id:q2.items[0].id,valor_unitario:25,nao_cotado:false}]});
 const o2=(await call('gerar_pedidos',{id:q2.id,selections:[{quotation_item_id:q2.items[0].id,supplier_id:supplier,quantidade:4}]})).orders[0];
 const invoice={id:o2.id,nota:{chave_nfe:'1'.repeat(44),numero_nfe:'55',cnpj_fornecedor:'123',valor_total:100},items:[{material_id:material,compras_item_id:o2.items[0].id,quantidade:4,valor_unitario:25}]};
 await assert.rejects(()=>call('nota_fiscal',{...invoice,nota:{...invoice.nota,cnpj_fornecedor:'999'}}),/Emitente/);
 await call('nota_fiscal',invoice);
 await assert.rejects(()=>call('nota_fiscal',invoice),/já importada/);
 await db.query('update insumos set estoque_atual=4 where id=$1',[material]);
 await db.query("update almoxarifado_compras set status='recebido' where compras_pedido_id=$1",[o2.id]);
 assert.equal((await call('consultar',{id:o2.id})).status,'recebido');
 await assert.rejects(()=>call('cancelar_pedido',{id:o2.id,motivo:'Teste'}),/recebimento/);
 const rnc=await call('criar_rnc',{id:o2.id,item_id:o2.items[0].id,quantidade:1,descricao:'Peça manchada'});
 assert.equal((await db.query('select estoque_atual from insumos')).rows[0].estoque_atual,'3');
 await call('decidir_rnc',{id:rnc.id,decisao:'aceitar',observacao:'Aprovado após análise'});
 assert.equal((await db.query('select estoque_atual from insumos')).rows[0].estoque_atual,'4');
 await assert.rejects(()=>call('decidir_rnc',{id:rnc.id,decisao:'aceitar',observacao:'Repetido'}),/não está aberta/);
 const audit=await db.query('select count(*)::int as n from compras_auditoria');assert.ok(audit.rows[0].n>=6);
 console.log('OK - isolamento por empresa, cotação, proposta, pedido, duplicação, cancelamento, NF-e, recebimento, RNC e estoque');
 await db.close();
}
module.exports={createDB};
if(require.main===module)main().catch(e=>{console.error(e);process.exitCode=1;});
